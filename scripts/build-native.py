"""Build actual standalone Windows executables using official Godot templates.
Run with --templates-dir containing windows_release_x86_64.exe (and optional
linux_release.x86_64). An optional NSIS compiler builds compressed Windows installers after native export.
No campaign data or artist PNG is regenerated by this command.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[1]

def run(command,env,cwd=ROOT):
    r=subprocess.run(command,cwd=cwd,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,timeout=240)
    if r.returncode or 'SCRIPT ERROR:' in r.stdout or 'ERROR:' in r.stdout:
        raise RuntimeError(r.stdout)
    print(r.stdout[-1000:])

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--templates-dir',type=Path,required=True)
    p.add_argument('--godot',default='godot')
    p.add_argument('--makensis',help='Optional NSIS compiler to create direct-download installers')
    p.add_argument('--linux-check',action='store_true')
    args=p.parse_args()
    out=ROOT/'build';out.mkdir(exist_ok=True)
    cache=ROOT/'.godot/native-templates';cache.mkdir(parents=True,exist_ok=True)
    names=['windows_release_x86_64.exe']+(['linux_release.x86_64'] if args.linux_check else [])
    for name in names:
        source=args.templates_dir/name
        if not source.is_file():raise FileNotFoundError(source)
        shutil.copy2(source,cache/name)
        (cache/name).chmod(0o755)
    env=dict(os.environ)
    for key,name in [('XDG_DATA_HOME','user'),('XDG_CONFIG_HOME','config'),('XDG_CACHE_HOME','cache')]:
        env.setdefault(key,str(out/name))
    run([args.godot,'--headless','--editor','--path',str(ROOT),'--import','--quit'],env)
    targets=[('Windows Normal','Poliquetos-Normal.exe'),('Windows Pruebas','Poliquetos-Pruebas.exe')]
    if args.linux_check:targets.append(('Linux Verification','poliquetos-linux.x86_64'))
    manifest=[]
    for preset,name in targets:
        target=out/name
        run([args.godot,'--headless','--path',str(ROOT),'--export-release',preset,str(target)],env)
        # Test the exported pack, never substitute an editor-only startup check.
        with tempfile.TemporaryDirectory(prefix='poliquetos-build-check-') as clean:
            run([args.godot,'--headless','--main-pack',str(target),'--','--verify-export'],env,cwd=clean)
            run([args.godot,'--headless','--main-pack',str(target),'--script',str(ROOT/'native-tests/export_stage_probe.gd')],env,cwd=clean)
        manifest.append({'file':name,'bytes':target.stat().st_size,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'preset':preset})
    if args.makensis:
        deliveries=ROOT/'entregas';deliveries.mkdir(exist_ok=True)
        nsis_env=dict(env)
        nsis_root=Path(args.makensis).resolve().parents[1]/'share/nsis'
        if nsis_root.is_dir():nsis_env['NSISDIR']=str(nsis_root)
        for edition in ('Normal','Pruebas'):
            target=deliveries/f'Poliquetos-{edition}-Instalar.exe'
            run([args.makensis,'-V2',f'-DEDITION={edition}',f'-DGAME_EXE={out/f"Poliquetos-{edition}.exe"}',f'-DOUTFILE={target}',str(ROOT/'scripts/install-native.nsi')],nsis_env)
            manifest.append({'file':str(target.relative_to(ROOT)),'bytes':target.stat().st_size,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'preset':edition+' installer'})
        (deliveries/'SHA256.json').write_text(json.dumps(manifest[-2:],indent=2)+'\n')
    (out/'SHA256.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
